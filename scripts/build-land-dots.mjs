// Builds src/lib/globe/land-dots.data.ts: which Fibonacci-sphere points fall on land,
// and which fall in the highlighted countries. Deterministic; run with `npm run build:land`.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { feature } from "topojson-client";
import { countryAt, fibonacciPoint, prepareCountries } from "./lib/geo.mjs";

const require = createRequire(import.meta.url);
const SIZES = [18000, 30000];
/** ISO 3166-1 numeric ids. Singapore (702) is not in the 110m data, so it has a marker only. */
const HIGHLIGHT = { india: 356, vietnam: 704, china: 156, indonesia: 360, kenya: 404 };

/** Land indices and highlight lists for n points. */
function computeLandDots(prepared, n) {
  const land = [];
  const highlight = Object.fromEntries(Object.keys(HIGHLIGHT).map((k) => [k, []]));
  const byId = new Map(Object.entries(HIGHLIGHT).map(([k, id]) => [id, k]));
  for (let i = 0; i < n; i++) {
    const { lon, lat } = fibonacciPoint(i, n);
    const id = countryAt(prepared, lon, lat);
    if (id == null) continue;
    land.push(i);
    const key = byId.get(id);
    if (key) highlight[key].push(i);
  }
  return { land, highlight };
}

function loadCountries() {
  const topo = JSON.parse(readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8"));
  return prepareCountries(feature(topo, topo.objects.countries).features);
}

const bitset = (indices, n) => {
  const bytes = new Uint8Array(Math.ceil(n / 8));
  for (const i of indices) bytes[i >> 3] |= 1 << (i & 7);
  return Buffer.from(bytes).toString("base64");
};

const deltas = (indices) => indices.map((v, k) => (k === 0 ? v : v - indices[k - 1]));

function render(prepared) {
  const lines = [
    "// Generated by scripts/build-land-dots.mjs from world-atlas countries-110m. Do not edit.",
    "// land: base64 bitset over Fibonacci-sphere points (bit i = byte[i >> 3] & (1 << (i & 7))).",
    "// highlight: delta-encoded ascending point indices per highlighted country.",
    "export const LAND_DOTS = {",
  ];
  for (const n of SIZES) {
    const { land, highlight } = computeLandDots(prepared, n);
    lines.push(`  ${n}: {`);
    lines.push(`    land: "${bitset(land, n)}",`);
    lines.push("    highlight: {");
    for (const [key, list] of Object.entries(highlight)) lines.push(`      ${key}: [${deltas(list).join(", ")}],`);
    lines.push("    },");
    lines.push("  },");
  }
  lines.push("} as const;", "");
  return lines.join("\n");
}

const out = fileURLToPath(new URL("../src/lib/globe/land-dots.data.ts", import.meta.url));
writeFileSync(out, render(loadCountries()), "utf8");
console.log(`wrote ${out}`);
